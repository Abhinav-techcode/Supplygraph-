package com.supplygraph.domain.model.provenance;

/**
 * Categorization of data provenance to distinguish real operational data from synthetic,
 * simulated, or AI-generated artifacts.
 */
public enum ProvenanceType {
    REAL_IMPORTED("Authoritative data ingested from enterprise ERP/WMS/MES software integrations"),
    MANUAL_OPERATOR("Direct manual input from authorized human operators"),
    SYNTHETIC_DEVELOPMENT("Synthetic baseline test data generated for scenario validation"),
    SIMULATION_OUTPUT("Stochastic or discrete-event simulation output from evaluation engines"),
    AI_PROPOSAL("Hypothetical recovery proposal generated by bounded AI agents (Non-authoritative)"),
    DETERMINISTIC_CALCULATION("Mathematically verified calculation derived deterministically from state");

    private final String description;

    ProvenanceType(String description) {
        this.description = description;
    }

    public String getDescription() {
        return description;
    }

    public boolean isAuthoritative() {
        return this == REAL_IMPORTED || this == MANUAL_OPERATOR || this == DETERMINISTIC_CALCULATION;
    }
}

